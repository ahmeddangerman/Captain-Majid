#!/usr/bin/env python3
"""Replay explicitly captured ordinary-pass defender choices in original order.

The caller supplies private instruction-boundary indices for the mode change
and each defender choice. NMI memory/carry and travel events are captured;
AI decisions and presentation are not generated by this comparison.
"""
import argparse
import re
import subprocess
import sys
from pathlib import Path

from verify_captured_control_chain import menu_wait_events, trace_data
from verify_captured_pass_target import compare_confirmed_target
from verify_player7_pass_end_to_end import prepare_output


def compare_defenses(actual, raw, original_target, phase, count):
    if len(actual) != 440 or actual[:10] != b'CMJSESSION' or actual[10] != 150:
        raise ValueError('boundary defenses: invalid native session format or length')
    if int.from_bytes(actual[258:260], 'little') != phase:
        raise ValueError(f'boundary defenses, session.phase: native {int.from_bytes(actual[258:260], "little")}, expected {phase}')
    prior = bytearray(actual[:429])
    prior[10] = 149
    prior[258:260] = (332).to_bytes(2, 'little')
    # Original AI reuses candidate scratch after target confirmation; compare
    # the saved candidate context to its actual earlier target boundary.
    adjusted = bytearray(raw)
    for address in (0x430, 0x625, 0x431, 0x432, 0x433, 0x434):
        adjusted[address] = original_target[address]
    try:
        compare_confirmed_target(prior, adjusted)
    except ValueError as error:
        raise ValueError(str(error).replace('target.confirmed', 'defenses')) from error
    if actual[429] != count:
        raise ValueError(f'boundary defenses, choices.count: native {actual[429]}, expected {count}')
    for slot in range(5):
        for offset, address, label in ((430, 0x60b, 'action'), (435, 0x606, 'subtype')):
            wanted = raw[address + slot] if slot < count else 0
            if actual[offset + slot] != wanted:
                raise ValueError(f'boundary defenses, choices[{slot}].{label}: native {actual[offset + slot]}, original {wanted}')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ('trace-directory', 'source', 'pack', 'exe', 'output'):
        parser.add_argument('--' + name, type=Path, required=True)
    parser.add_argument('--initial-index', type=int, required=True)
    parser.add_argument('--mode-boundary-index', type=int, required=True)
    parser.add_argument('--choice-boundary-index', type=int, action='append', required=True)
    parser.add_argument('--prepared-boundary-index', type=int, help='original bank26 804F attacker-prepared boundary')
    args = parser.parse_args()
    if not 0 <= args.initial_index <= 255:
        raise ValueError('Initial random index must be a byte')
    lines, pcs, ram = trace_data(args.trace_directory)
    start = pcs.index('D84B')
    original = ram(start)
    if args.initial_index != original[0xe1]:
        raise ValueError(f'boundary pass.confirmed, random.index: native {args.initial_index}, original {original[0xe1]}')
    compare_confirmed_target(args.source.read_bytes(), original)
    boundaries = [args.mode_boundary_index, *args.choice_boundary_index]
    if boundaries != sorted(set(boundaries)) or boundaries[0] <= start or boundaries[-1] >= len(pcs):
        raise ValueError('Mode and choice boundary indices must be unique, ordered and after confirmation')
    if len(args.choice_boundary_index) != original[0x600] or not 1 <= original[0x600] <= 5:
        raise ValueError('Choice boundaries must cover the observed opposing prefix')
    if pcs[boundaries[0]] != 'C9C5' or pcs[boundaries[-1]] != '804C' or ram(boundaries[-1])[0x24] != 26:
        raise ValueError('Trace does not end at the supported original attacker-preparation entry')
    output = prepare_output(args.output, Path(__file__).resolve().parents[1])
    source, index, previous, operation, count = args.source.resolve(), args.initial_index, start, 0, 0
    for slot, boundary in enumerate(boundaries):
        last = next(i for i in range(boundary - 1, previous, -1) if pcs[i] == 'E406')
        rows, checked = menu_wait_events(lines, pcs, ram, previous, last + 1)
        if checked != last:
            raise ValueError('boundary defenses.wait: incomplete recorded travel')
        operation += 1
        events = output / f'{operation:03d}-events.txt'
        events.write_text('CMJNMISEQ1\n' + '\n'.join(rows) + '\n')
        waiting = output / f'{operation:03d}-wait.cmjsession'
        run = subprocess.run([str(args.exe.resolve()), str(args.pack.resolve()), str(source),
                              '--advance-observed-nmi-sequence', str(events), str(index), '--capture', str(waiting)],
                             capture_output=True, text=True, timeout=30)
        if run.returncode:
            raise RuntimeError(f'boundary defenses.wait[{slot}]: {run.stderr.strip()}')
        indices = re.findall(r'final random index (\d+);', run.stdout)
        if indices != [str(ram(last)[0xe1])]:
            raise ValueError(f'boundary defenses.wait[{slot}], random.index: native {indices}, original {ram(last)[0xe1]}')
        index = int(indices[0])
        if slot == 0:
            compare_confirmed_target(waiting.read_bytes(), ram(last))
            command = ['--begin-ordinary-pass-defenses']
        else:
            compare_defenses(waiting.read_bytes(), ram(last), original, 333, count)
            defender = original[0x601 + count]
            action, subtype = ram(boundary)[0x60b + count], ram(boundary)[0x606 + count]
            if ram(boundary)[0x442] != defender:
                raise ValueError(f'boundary defenses.choice[{count + 1}]: original defender is out of order')
            command = ['--record-ordinary-pass-defense', str(defender), str(action), str(subtype)]
            count += 1
        operation += 1
        destination = output / f'{operation:03d}-state.cmjsession'
        run = subprocess.run([str(args.exe.resolve()), str(args.pack.resolve()), str(waiting), *command,
                              '--capture', str(destination)], capture_output=True, text=True, timeout=30)
        if run.returncode:
            raise RuntimeError(f'boundary defenses.choice[{slot}]: {run.stderr.strip()}')
        phase = 334 if count == original[0x600] else 333
        compare_defenses(destination.read_bytes(), ram(boundary), original, phase, count)
        if index != ram(boundary)[0xe1]:
            raise ValueError(f'boundary defenses.choice[{slot}], random.index: native {index}, original {ram(boundary)[0xe1]}')
        source = destination
        # A C9C5 milestone is before that random call, which belongs to the next interval.
        previous = boundary - 1 if pcs[boundary] == 'C9C5' else boundary
    if args.prepared_boundary_index is not None:
        prepared = args.prepared_boundary_index
        if (prepared <= boundaries[-1] or prepared >= len(pcs) or pcs[prepared] != '804F' or ram(prepared)[0x24] != 26 or
                any(pcs[i] == 'C9C5' for i in range(boundaries[-1] + 1, prepared))):
            raise ValueError('boundary pass.prepared: unsupported original ordering or bank')
        operation += 1
        destination = output / f'{operation:03d}-prepared.cmjsession'
        run = subprocess.run([str(args.exe.resolve()), str(args.pack.resolve()), str(source),
                              '--prepare-ordinary-pass', '--capture', str(destination)],
                             capture_output=True, text=True, timeout=30)
        if run.returncode:
            raise RuntimeError(f'boundary pass.prepared: {run.stderr.strip()}')
        try:
            compare_defenses(destination.read_bytes(), ram(prepared), original, 335, count)
        except ValueError as error:
            raise ValueError(str(error).replace('boundary defenses', 'boundary pass.prepared')) from error
        if index != ram(prepared)[0xe1]:
            raise ValueError(f'boundary pass.prepared, random.index: native {index}, original {ram(prepared)[0xe1]}')
        source = destination
    print(f'Matched ordered mode change and {count} explicitly recorded defender choices'
          f'{" and attacker preparation" if args.prepared_boundary_index is not None else " to attacker-preparation entry"}; '
          f'final random index {index}; checkpoint {source}.')


if __name__ == '__main__':
    try:
        main()
    except (OSError, ValueError, RuntimeError, StopIteration, subprocess.SubprocessError) as error:
        print(f'Captured pass defense replay stopped: {error}', file=sys.stderr)
        sys.exit(1)
