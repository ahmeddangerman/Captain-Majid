#!/usr/bin/env python3
"""Compare prepared kickoff control setup with captured original observations."""
import argparse
import json
import subprocess
from pathlib import Path
from check_keeper_saves_original import post_save_checkpoint


def checkpoint(ram, phase):
    data = bytearray(post_save_checkpoint(ram, phase))
    data[361:365] = bytes([1, ram[0x28], ram[0x29], ram[0x629]])
    data[365:368] = bytes([1, ram[0x308], ram[0x38c]])
    if phase == 64:
        data[368:370] = bytes([1, ram[0x5fc]])
    return bytes(data)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    for name in ('pack', 'observations_dir', 'output_dir'):
        p.add_argument(name, type=Path)
    a = p.parse_args()
    observations = json.loads((a.observations_dir / 'observation.json').read_text())
    out = a.output_dir.resolve()
    if out.is_relative_to(Path(__file__).resolve().parents[1]):
        p.error('Private outputs must stay outside checkout')
    out.mkdir(parents=True, exist_ok=False)
    binary = str(Path('build/captain-phase-session').resolve())
    for case in observations['cases']:
        name = f"s{case['side']}-l{case['left_formation']}-r{case['right_formation']}"
        before = (a.observations_dir / f'{name}-before.bin').read_bytes()
        after = (a.observations_dir / f'{name}-after.bin').read_bytes()
        source = out / f'{name}-input.cmjsession'
        source.write_bytes(checkpoint(before, 64))
        target = out / f'{name}-native.cmjsession'
        run = subprocess.run([binary, str(a.pack.resolve()), str(source), '--setup-control',
                              '--capture', str(target)], capture_output=True, text=True, timeout=30)
        if run.returncode:
            raise RuntimeError(f'{name}: native failed: {run.stderr}')
        actual, expected = target.read_bytes(), checkpoint(after, 9)
        if actual != expected:
            raise RuntimeError(f'{name} mismatch: '
                               f'{[(i, a, b) for i, (a, b) in enumerate(zip(actual, expected)) if a != b]}')
    (out / 'verification.json').write_text(json.dumps({
        'cases':len(observations['cases']),
        'scope':'Compares represented original E0DF..E145 against native setup for prepared kickoff inputs. Display36 assumed acknowledged; control presentation uses host acknowledgements, with no actual NMI, audio or PPU execution. The original input observations were generated by trace_kickoff_control_original.py.'
    }, indent=2) + '\n')
    print(f"{len(observations['cases'])} kickoff control comparisons match: {out}")


if __name__ == '__main__':
    main()
