#!/usr/bin/env python3
"""Compare explicitly supplied ordinary-pass defender prefixes across private cases.

The start RAM is the original confirmed target; preparation RAM is the original
attacker-preparation entry after defender choices. Choices are supplied from the
latter capture, not generated by native AI. Intermediate timing is not modelled.
"""
import argparse
import subprocess
import sys
from pathlib import Path

from verify_captured_pass_defenses import compare_defenses, compare_first_defender, compare_first_defender_result, compare_first_contact, compare_dispatch_clock, compare_movement
from verify_captured_pass_target import compare_confirmed_target
from verify_observed_world_round import checkpoint
from verify_player7_pass_end_to_end import case_ids, prepare_output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ('starts', 'preparations', 'pack', 'exe', 'output'):
        parser.add_argument('--' + name, type=Path, required=True)
    parser.add_argument('--start-suffix', required=True)
    parser.add_argument('--preparation-suffix', required=True)
    parser.add_argument('--prepared-suffix', help='optional original attacker-prepared RAM suffix')
    parser.add_argument('--first-defender-suffix', help='optional original first-defender-prepared RAM suffix')
    parser.add_argument('--first-comparison-suffix', help='optional original first-defender-compared RAM suffix')
    parser.add_argument('--first-contact-suffix', help='optional original first contact clock RAM suffix')
    parser.add_argument('--next-defender-pattern', help='original preparation suffix with {slot} as one-based defender index')
    parser.add_argument('--next-comparison-pattern', help='original comparison suffix with {slot}')
    parser.add_argument('--next-contact-pattern', help='original contact suffix with {slot}')
    parser.add_argument('--dispatch-suffix', help='original final dispatch clock suffix')
    parser.add_argument('--movement-original', type=Path, help='directory containing original pass-handoff RAM captures')
    parser.add_argument('--movement-suffix', help='original pass-handoff RAM suffix')
    parser.add_argument('--comparison-score', type=int, help='original observed comparison score')
    parser.add_argument('--comparison-result', type=int, help='original observed result code')
    parser.add_argument('--comparison-strength', type=int, help='original observed defender strength')
    parser.add_argument('--comparison-content', nargs=7, type=int, metavar=('RANGE', 'OFFSET', 'ELIGIBLE', 'T0', 'T1', 'T2', 'T3'))
    parser.add_argument('--expected-cases', type=int, required=True)
    args = parser.parse_args()
    if args.first_defender_suffix and not args.prepared_suffix:
        raise ValueError('First defender comparison requires attacker-prepared observations')
    if args.first_contact_suffix and not args.first_comparison_suffix:
        raise ValueError('First contact requires the original comparison boundary')
    patterns = (args.next_defender_pattern, args.next_comparison_pattern, args.next_contact_pattern)
    if any(patterns) and (not all(patterns) or not args.first_contact_suffix or any('{slot}' not in pattern for pattern in patterns)):
        raise ValueError('Additional defenders require all three suffix patterns and the first contact')
    if args.dispatch_suffix and not args.next_defender_pattern:
        raise ValueError('Dispatch comparison requires the full defender sequence')
    if (args.movement_original is None) != (args.movement_suffix is None) or (args.movement_suffix and not args.dispatch_suffix):
        raise ValueError('Movement requires a private original directory, suffix and dispatch')
    if args.first_comparison_suffix and (not args.first_defender_suffix or any(value is None or not 0 <= value <= 255 for value in
            (args.comparison_score, args.comparison_result, args.comparison_strength))):
        raise ValueError('Defender comparison requires preparation and byte-valued original score, result and strength')
    if args.first_comparison_suffix and (args.comparison_content is None or any(not 0 <= value <= 255 for value in args.comparison_content) or args.comparison_content[2] > 1):
        raise ValueError('Defender comparison requires byte-valued direct table content and boolean eligibility')
    cases = case_ids(args.starts, args.start_suffix, args.expected_cases)
    output = prepare_output(args.output, Path(__file__).resolve().parents[1])

    def invoke(source, destination, *options):
        run = subprocess.run([str(args.exe.resolve()), str(args.pack.resolve()), str(source), *map(str, options),
                              '--capture', str(destination)], capture_output=True, text=True, timeout=30)
        if run.returncode:
            raise RuntimeError(run.stderr.strip())

    for case in cases:
        original = (args.starts / f'{case}{args.start_suffix}').read_bytes()
        preparation = (args.preparations / f'{case}{args.preparation_suffix}').read_bytes()
        if len(original) != 2048 or len(preparation) != 2048 or original[0x430] > 4 or not 1 <= original[0x600] <= 5:
            raise ValueError(f'case {case}, boundary pass.confirmed: invalid original context')
        try:
            entry = output / f'{case}-entry.cmjsession'
            entry.write_bytes(checkpoint(original, 19))
            initial = output / f'{case}-initial.cmjsession'
            invoke(entry, initial, '--begin-ordinary-human-pass-target')
            state = bytearray(initial.read_bytes())
            state[419] = original[0x624]
            count = original[0x430]
            state[421:428] = bytes((1, count, original[0x625],
                                    *(original[0x431 + i] if i < count else 0 for i in range(4))))
            target = output / f'{case}-target.cmjsession'
            target.write_bytes(state)
            confirmed = output / f'{case}-confirmed.cmjsession'
            invoke(target, confirmed, '--confirm-ordinary-human-pass-target')
            compare_confirmed_target(confirmed.read_bytes(), original)
            current = output / f'{case}-begin.cmjsession'
            invoke(confirmed, current, '--begin-ordinary-pass-defenses')
            for slot in range(original[0x600]):
                destination = output / f'{case}-choice-{slot + 1}.cmjsession'
                invoke(current, destination, '--record-ordinary-pass-defense', original[0x601 + slot],
                       preparation[0x60b + slot], preparation[0x606 + slot])
                current = destination
            compare_defenses(current.read_bytes(), preparation, original, 334, original[0x600])
            if args.prepared_suffix:
                prepared = output / f'{case}-prepared.cmjsession'
                invoke(current, prepared, '--prepare-ordinary-pass')
                compare_defenses(prepared.read_bytes(), (args.preparations / f'{case}{args.prepared_suffix}').read_bytes(),
                                 original, 335, original[0x600])
                if args.first_defender_suffix:
                    defender_raw = (args.preparations / f'{case}{args.first_defender_suffix}').read_bytes()
                    # These are explicit original presentation samples; this does not run presentation.
                    current = prepared.read_bytes()
                    presentation = output / f'{case}-presentation.txt'
                    rows = []
                    if current[305] != defender_raw[0x532]:
                        rows.append(f'M {defender_raw[0x532]}')
                    if current[299] != defender_raw[0x517]:
                        rows.append(f'F {defender_raw[0x517]}')
                    presentation.write_text('CMJNMISEQ1\n' + ''.join(row + '\n' for row in rows))
                    waiting = output / f'{case}-presentation.cmjsession'
                    invoke(prepared, waiting, '--advance-observed-nmi-sequence', presentation, 0)
                    defender = output / f'{case}-defender.cmjsession'
                    invoke(waiting, defender, '--prepare-first-ordinary-pass-defender', defender_raw[0x44e])
                    compare_first_defender(defender.read_bytes(), defender_raw, original, original[0x600])
                    if args.first_comparison_suffix:
                        compared = output / f'{case}-compared.cmjsession'
                        invoke(defender, compared, '--compare-first-ordinary-pass-defender', *args.comparison_content)
                        comparison_raw = (args.preparations / f'{case}{args.first_comparison_suffix}').read_bytes()
                        compare_first_defender_result(compared.read_bytes(), comparison_raw, original, original[0x600],
                                                      args.comparison_score, args.comparison_result, args.comparison_strength)
                        if args.first_contact_suffix:
                            contact = output / f'{case}-contact.cmjsession'
                            invoke(compared, contact, '--advance-first-ordinary-pass-contact')
                            contact_raw = (args.preparations / f'{case}{args.first_contact_suffix}').read_bytes()
                            compare_first_contact(contact.read_bytes(), contact_raw, original, original[0x600],
                                                  args.comparison_score, args.comparison_result, args.comparison_strength)
                            if args.next_defender_pattern:
                                for slot in range(1, original[0x600]):
                                    prepared_next = output / f'{case}-defender-{slot + 1}.cmjsession'
                                    invoke(contact, prepared_next, '--prepare-next-ordinary-pass-defender')
                                    next_raw = (args.preparations / f'{case}{args.next_defender_pattern.format(slot=slot + 1)}').read_bytes()
                                    compare_first_defender(prepared_next.read_bytes(), next_raw, original, original[0x600], slot)
                                    compared_next = output / f'{case}-compared-{slot + 1}.cmjsession'
                                    invoke(prepared_next, compared_next, '--compare-next-ordinary-pass-defender', *args.comparison_content)
                                    comparison_raw = (args.preparations / f'{case}{args.next_comparison_pattern.format(slot=slot + 1)}').read_bytes()
                                    compare_first_defender_result(compared_next.read_bytes(), comparison_raw, original, original[0x600],
                                                                  args.comparison_score, args.comparison_result, args.comparison_strength, slot)
                                    contact = output / f'{case}-contact-{slot + 1}.cmjsession'
                                    invoke(compared_next, contact, '--advance-next-ordinary-pass-contact')
                                    contact_raw = (args.preparations / f'{case}{args.next_contact_pattern.format(slot=slot + 1)}').read_bytes()
                                    compare_first_contact(contact.read_bytes(), contact_raw, original, original[0x600],
                                                          args.comparison_score, args.comparison_result, args.comparison_strength, slot)
                                if args.dispatch_suffix:
                                    dispatch = output / f'{case}-dispatch.cmjsession'
                                    invoke(contact, dispatch, '--advance-ordinary-pass-dispatch-clock')
                                    dispatch_raw = (args.preparations / f'{case}{args.dispatch_suffix}').read_bytes()
                                    compare_dispatch_clock(dispatch.read_bytes(), dispatch_raw, original, original[0x600],
                                                           args.comparison_score, args.comparison_result, args.comparison_strength, original[0x600] - 1)
                                    if args.movement_suffix:
                                        events = output / f'{case}-movement-events.txt'
                                        events.write_text('CMJNMISEQ1\n' + ''.join(f'P {slot}\n' for slot in range(22)))
                                        moved = output / f'{case}-movement.cmjsession'
                                        invoke(dispatch, moved, '--advance-observed-pass-movement', events, 0)
                                        movement_raw = (args.movement_original / f'{case}{args.movement_suffix}').read_bytes()
                                        compare_movement(moved.read_bytes(), movement_raw, comparison_raw, original, original[0x600],
                                                         args.comparison_score, args.comparison_result, args.comparison_strength, original[0x600] - 1)
        except (ValueError, RuntimeError) as error:
            raise ValueError(f'case {case}, {error}') from error
    print(f'Matched {len(cases)} original attacker-preparation entries'
          f'{" through field movement and pass handoff" if args.movement_suffix else " through dispatch clock" if args.dispatch_suffix else " and all recorded defender contacts" if args.next_defender_pattern else " and first contact clock" if args.first_contact_suffix else " and first-defender comparison" if args.first_comparison_suffix else " and first-defender preparation" if args.first_defender_suffix else " and prepared states" if args.prepared_suffix else ""} with explicitly supplied defender choices.')


if __name__ == '__main__':
    try:
        main()
    except (OSError, ValueError, RuntimeError, subprocess.SubprocessError) as error:
        print(f'Ordinary pass defense comparison stopped: {error}', file=sys.stderr)
        sys.exit(1)
